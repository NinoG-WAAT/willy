/** Words that may stay as they are: the app name and the typed confirmation word. */
const KEEP_TOKENS = new Set(["DELETE", "Willycrumbs"]);

/**
 * Text that is the same in both languages on purpose: the bilingual language label and the
 * language names (each is written in its own language).
 */
export const ALWAYS_ALLOWED_TEXT: readonly string[] = ["Language / Langue", "English", "Français"];

export interface EnglishHit {
  word: string;
  in: string;
}

/**
 * English words left in some interface texts. `ownerText` lists strings the owner wrote (titles,
 * note text, folder names): they are removed before the words are looked at. A token with an
 * underscore is a code (`storage_unavailable`), not a sentence, and is left alone.
 */
export function englishLeftovers(
  texts: readonly string[],
  ownerText: readonly (string | RegExp)[] = [],
): EnglishHit[] {
  const english = new Set(ENGLISH_UI_WORDS);
  const hits: EnglishHit[] = [];
  for (const text of texts) {
    let rest = text;
    for (const allowed of [...ALWAYS_ALLOWED_TEXT, ...ownerText]) {
      rest =
        typeof allowed === "string" ? rest.split(allowed).join(" ") : rest.replace(allowed, " ");
    }
    // An identifier (a reference, a code) has a digit or an underscore in it: skip the whole chunk.
    for (const chunk of rest.split(/\s+/u)) {
      if (/[\d_]/u.test(chunk)) continue;
      for (const token of chunk.split(/[^\p{L}]+/u)) {
        if (token === "" || KEEP_TOKENS.has(token)) continue;
        if (english.has(token.toLowerCase())) {
          hits.push({ word: token, in: text.trim().slice(0, 100) });
        }
      }
    }
  }
  return hits;
}
